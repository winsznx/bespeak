#!/usr/bin/env node
/**
 * Compile the execution receipts into a module the app can serve anywhere.
 *
 * Receipts are files on disk because evidence a server can silently rewrite is not
 * evidence. That works in development and it works for anyone auditing the repo, but the
 * Cloudflare worker has no filesystem, so the proof pages 404'd in production while the
 * receipts sat in the repo the whole time.
 *
 * This copies them verbatim into a generated module at build time. The bytes are the same
 * bytes; nothing is reformatted or recomputed, so a receipt served from the deployed site
 * still hashes to its own receiptId.
 */
import {readdirSync, readFileSync, writeFileSync, mkdirSync} from "node:fs";
import {join, dirname} from "node:path";
import {fileURLToPath} from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, "..", "..", "..", "evidence", "executions");
const OUT = join(here, "..", "src", "lib", "receipts.generated.ts");

let files = [];
try {
  files = readdirSync(SRC).filter((f) => f.endsWith(".json"));
} catch {
  // No receipts yet is a normal state before the first run, not a build failure.
}

const entries = [];
for (const f of files.sort()) {
  const raw = readFileSync(join(SRC, f), "utf8");
  const parsed = JSON.parse(raw);
  if (!parsed.receiptId) {
    console.warn(`  skipped ${f}: no receiptId`);
    continue;
  }
  entries.push([parsed.receiptId, raw]);
}

const body = entries
  .map(([id, raw]) => `  ${JSON.stringify(id)}: ${raw.trim()} as unknown as StoredReceipt,`)
  .join("\n");

mkdirSync(dirname(OUT), {recursive: true});
writeFileSync(
  OUT,
  `// Generated by scripts/bundle-receipts.mjs. Do not edit.
// Source of truth is evidence/executions/ at the repo root.
import type {StoredReceipt} from "./receipts";

export const BUNDLED_RECEIPTS: Record<string, StoredReceipt> = {
${body}
};
`,
);
console.log(`bundled ${entries.length} receipt(s) -> src/lib/receipts.generated.ts`);
